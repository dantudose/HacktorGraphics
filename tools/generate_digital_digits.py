#!/usr/bin/env python3
"""Regenerate include/DigitalDigits.hpp from original monoline geometry.

Usage: python3 tools/generate_digital_digits.py
Requires Pillow >= 9.1 (python3 -m pip install Pillow). No font files or downloads.
The fixed 8x raster, stroke width and quantization make output deterministic.
"""

from pathlib import Path

from PIL import Image, ImageDraw


# Original digit paths in a 38 x 64 logical coordinate space.
# M = move, L = line, C = cubic Bezier (two controls and endpoint).
PATHS = [
    [('M', 19, 1), ('C', 5, 1, 2, 14, 2, 32),
     ('C', 2, 50, 5, 63, 19, 63), ('C', 33, 63, 36, 50, 36, 32),
     ('C', 36, 14, 33, 1, 19, 1)],
    [('M', 8, 12), ('L', 22, 1), ('L', 22, 63)],
    [('M', 3, 14), ('C', 3, -1, 34, -5, 36, 12),
     ('C', 39, 28, 12, 48, 2, 63), ('L', 37, 63)],
    [('M', 3, 6), ('C', 16, -3, 35, -1, 35, 15),
     ('C', 35, 25, 30, 31, 20, 31), ('C', 31, 31, 37, 37, 37, 48),
     ('C', 37, 65, 16, 67, 3, 57)],
    [('M', 29, 63), ('L', 29, 1), ('L', 1, 43), ('L', 39, 43)],
    [('M', 35, 1), ('L', 6, 1), ('L', 3, 28),
     ('C', 30, 17, 40, 29, 36, 48), ('C', 33, 65, 10, 69, 2, 56)],
    [('M', 33, 3), ('C', 15, -3, 2, 14, 2, 38),
     ('C', 2, 72, 37, 69, 37, 45), ('C', 37, 23, 5, 21, 3, 39)],
    [('M', 1, 1), ('L', 38, 1), ('L', 13, 63)],
    [('M', 19, 31), ('C', 1, 31, 0, 1, 19, 1),
     ('C', 38, 1, 37, 31, 19, 31), ('C', -5, 31, -3, 63, 19, 63),
     ('C', 41, 63, 43, 31, 19, 31)],
    [('M', 35, 25), ('C', 33, 43, 1, 39, 2, 20),
     ('C', 2, -5, 37, -6, 37, 24), ('C', 37, 52, 27, 67, 8, 62)],
]

SCALE, WIDTH, HEIGHT = 8, 44, 68


def rasterize(path):
    image = Image.new('L', (WIDTH * SCALE, HEIGHT * SCALE))
    points = []
    for op, *coords in path:
        if op in ('M', 'L'):
            current = (coords[0], coords[1])
            points.append(current)
        else:
            x0, y0 = current
            x1, y1, x2, y2, x3, y3 = coords
            for step in range(1, 65):
                t = step / 64
                s = 1 - t
                points.append((
                    s**3*x0 + 3*s*s*t*x1 + 3*s*t*t*x2 + t**3*x3,
                    s**3*y0 + 3*s*s*t*y1 + 3*s*t*t*y2 + t**3*y3))
            current = (x3, y3)
    draw = ImageDraw.Draw(image)
    draw.line([((x + 2) * SCALE, (y + 2) * SCALE) for x, y in points],
              fill=255, width=18, joint='curve')
    for x, y in (points[0], points[-1]):
        x, y = (x + 2) * SCALE, (y + 2) * SCALE
        draw.ellipse((x - 8, y - 8, x + 8, y + 8), fill=255)
    image = image.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
    return [(value * 15 + 127) // 255 for value in image.getdata()]


def main():
    data, offsets = [], []
    for path in PATHS:
        pixels = rasterize(path)
        offsets.append(len(data))
        for y in range(HEIGHT):
            row = pixels[y * WIDTH:(y + 1) * WIDTH]
            x = 0
            while x < WIDTH:
                coverage, count = row[x], 1
                while (count < 16 and x + count < WIDTH
                       and row[x + count] == coverage):
                    count += 1
                data.append((coverage << 4) | (count - 1))
                x += count
    offsets.append(len(data))

    text = '''#pragma once

// Generated by tools/generate_digital_digits.py from original monoline geometry.
// Rasterized at 8x then reduced to 4-bit antialiased coverage.
// RLE byte: coverage in high nibble; run length minus one in low nibble.
// Runs stop at each row. Flash only; no font loading or heap.
// Each digit occupies 44 x 68 pixels, with a 44-pixel advance.
namespace watch { namespace digital_detail {
static const uint16_t digit_offsets[] PROGMEM = {
    ''' + ', '.join(map(str, offsets)) + '''
};
static const uint8_t digit_coverage[] PROGMEM = {
'''
    for start in range(0, len(data), 20):
        text += '    ' + ', '.join('0x%02x' % byte
                                   for byte in data[start:start + 20]) + ',\n'
    text += '};\n}} // namespace watch::digital_detail\n'
    output = Path(__file__).resolve().parents[1] / 'include/DigitalDigits.hpp'
    output.write_text(text, encoding='utf-8')
    print('Digit RLE flash:', len(data) + len(offsets) * 2, 'bytes')


if __name__ == '__main__':
    main()
